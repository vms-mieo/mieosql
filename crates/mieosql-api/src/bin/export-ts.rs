//! Export TypeScript bindings for the whole frontend contract.
//!
//! Usage: `cargo run -p mieosql-api --bin export-ts -- <output-dir>`

use std::path::{Path, PathBuf};

fn main() {
    let dir: PathBuf = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("bindings/ts"));

    if let Err(e) = std::fs::create_dir_all(&dir) {
        eprintln!("cannot create {}: {e}", dir.display());
        std::process::exit(1);
    }

    let cfg = ts_rs::Config::new().with_out_dir(&dir);

    if let Err(errors) = mieosql_api::export_manifest::export_all(&cfg) {
        eprintln!("failed to export some types:\n{errors}");
        std::process::exit(1);
    }

    if let Err(e) = write_barrel(&dir) {
        eprintln!("warning: could not write index.ts: {e}");
    }

    println!(
        "TypeScript bindings written to {} (API version {})",
        dir.display(),
        mieosql_api::API_VERSION
    );
}

/// Generate an `index.ts` barrel re-exporting every generated file.
fn write_barrel(dir: &Path) -> std::io::Result<()> {
    let mut names: Vec<String> = std::fs::read_dir(dir)?
        .filter_map(|entry| entry.ok())
        .filter_map(|entry| {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) == Some("ts") {
                path.file_stem()
                    .and_then(|s| s.to_str())
                    .map(|s| s.to_string())
            } else {
                None
            }
        })
        .filter(|name| name != "index")
        .collect();
    names.sort();

    let mut out = String::from(
        "// AUTO-GENERATED by `cargo run -p mieosql-api --bin export-ts` — do not edit.\n",
    );
    out.push_str(&format!("// API version: {}\n\n", mieosql_api::API_VERSION));
    for name in &names {
        out.push_str(&format!("export * from \"./{name}\";\n"));
    }
    std::fs::write(dir.join("index.ts"), out)
}
